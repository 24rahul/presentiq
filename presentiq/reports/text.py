"""Shared report generation utilities for PresentIQ."""


def generate_report(feedback, ai_provider, model, service, transcript_text):
    """Generate a plain-text feedback report from the feedback dict."""
    report_lines = [
        "PRESENTIQ - MEDICAL PRESENTATION FEEDBACK REPORT",
        "=" * 60,
        "",
        f"Service: {feedback.get('service', 'General Medicine')}",
        f"Presentation Format: {feedback.get('presentation_format', 'Standard')}",
        f"Performance Score: {feedback.get('overall_score', 'N/A')}/10",
        f"AI Provider: {ai_provider}",
        f"AI Model: {model}",
        "",
        "OVERALL ASSESSMENT:",
        feedback.get("overall_assessment", "No assessment provided."),
        "",
        "CLINICAL CONTENT:",
        feedback.get("clinical_content", "No feedback provided."),
        "",
        "CLINICAL REASONING:",
        feedback.get("clinical_reasoning", "No feedback provided."),
        "",
        "PRESENTATION STRUCTURE:",
        feedback.get("presentation_structure", "No feedback provided."),
        "",
    ]

    if feedback.get("plan_coherence_summary"):
        report_lines.extend(
            [
                "PLAN COHERENCE:",
                feedback["plan_coherence_summary"],
                "",
            ]
        )

    if feedback.get("semantic_density_summary"):
        report_lines.extend(
            [
                "INFORMATION EFFICIENCY:",
                feedback["semantic_density_summary"],
                "",
            ]
        )

    if feedback.get("communication_professionalism"):
        report_lines.extend(
            [
                "COMMUNICATION & PROFESSIONALISM:",
                feedback["communication_professionalism"],
                "",
            ]
        )

    report_lines.append("STRENGTHS:")
    for strength in feedback.get("strengths", []):
        report_lines.append(f"- {strength}")

    report_lines.extend(["", "AREAS FOR IMPROVEMENT:"])
    for area in feedback.get("areas_for_improvement", []):
        report_lines.append(f"- {area}")

    if feedback.get("service_specific_feedback"):
        report_lines.extend(
            [
                "",
                "SERVICE-SPECIFIC FEEDBACK:",
                feedback["service_specific_feedback"],
            ]
        )

    tp = feedback.get("teaching_points", [])
    if tp:
        report_lines.extend(["", "TEACHING POINTS:"])
        for point in tp:
            report_lines.append(f"- {point}")

    agent_results = feedback.get("_agent_results", {})

    contrastive = agent_results.get("contrastive_feedback", {})
    rewrites = contrastive.get("rewrites", [])
    if rewrites:
        report_lines.extend(["", "BEFORE / AFTER REWRITES:"])
        for rw in rewrites:
            report_lines.append(f"\n  [{rw.get('area', '')}]")
            report_lines.append(f"  Original: {rw.get('original', '')}")
            report_lines.append(f"  Improved: {rw.get('improved', '')}")
            report_lines.append(f"  Why: {rw.get('why_better', '')}")
            if rw.get("uses_illustrative_data"):
                report_lines.append(
                    "  Note: Bracketed values are illustrative — substitute patient's actual data."
                )

    debate = agent_results.get("debate", {})
    if debate.get("contested_points"):
        report_lines.extend(["", "DELIBERATION (Generous vs Strict):"])
        for cp in debate["contested_points"]:
            report_lines.append(
                f"\n  [{cp.get('dimension', '')}] Adjustment: {cp.get('adjustment', 'keep')}"
            )
            report_lines.append(f"  Generous: {cp.get('generous_view', '')}")
            report_lines.append(f"  Strict: {cp.get('strict_view', '')}")
            report_lines.append(f"  Resolution: {cp.get('resolution', '')}")

    anticipatory = agent_results.get("anticipatory_reasoning", {})
    if anticipatory.get("overall_impression"):
        report_lines.extend(
            [
                "",
                "ATTENDING INNER MONOLOGUE - OVERALL IMPRESSION:",
                anticipatory["overall_impression"],
            ]
        )
        unanswered = anticipatory.get("unanswered_questions", [])
        if unanswered:
            report_lines.append("")
            report_lines.append("UNANSWERED QUESTIONS:")
            for q in unanswered:
                report_lines.append(f"- {q}")

    report_lines.extend(
        [
            "",
            "=" * 60,
            "TRANSCRIPT:",
            transcript_text,
            "",
            "Generated by PresentIQ - Created by Rahul Gorijavolu and Emily Zhao at the Johns Hopkins University School of Medicine",
        ]
    )

    return "\n".join(report_lines)
